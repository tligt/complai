"""
branding_view.py — S52 (D-144): the Document branding section of the Company
profile page. Logo, main colour, font and footer line for the documents
RECOSA generates for this company (doc_theme.py builds them in).

Professional, Advisory and Enterprise. A Starter company sees what branding
does and an upgrade prompt; its documents use the house style.

Each save is a new version (brand_profiles). New documents use the newest;
documents already generated keep the look they were made with and record
which version that was.
"""

from __future__ import annotations
from i18n import tr  # S64 interface translation (D-164)

import html

import streamlit as st

import doc_theme as DT
from database import can_edit

_SAMPLE = """## 1. Who we are

This sample shows how your documents will look: headings, body text and a
table, in your colour and font, with your logo at the top of each page.

### 1.1 Contact

Write to us at the address below for any question about your data.

| Purpose | Legal basis | Kept for |
|---|---|---|
| Customer accounts | Contract | 3 years after the last order |
| Newsletter | Consent | Until you unsubscribe |
"""


def _preview(theme: DT.DocTheme, company: str) -> None:
    """A small HTML picture of a branded page, from the saved theme."""
    import base64
    head = DT.rgb_to_hex(theme.text)
    fill = theme.color
    on_fill = DT.rgb_to_hex(theme.header_text)
    logo = ""
    if theme.logo:
        b64 = base64.b64encode(theme.logo).decode()
        logo = f'<img src="data:image/png;base64,{b64}" style="height:34px;margin-bottom:10px">'
    font = html.escape(theme.font)
    footer = html.escape(theme.footer_text or "") if theme.branded else "Generated by RECOSA · recosa.eu"
    st.html(f"""
<div style="border:1px solid #E2E8F0;border-radius:8px;padding:18px 22px;background:#fff;
            font-family:'{font}',Arial,sans-serif;color:#333;max-width:560px">
  {logo}
  <div style="font-size:20px;font-weight:700;color:{head};border-bottom:2px solid {fill};
              padding-bottom:4px">Privacy Policy</div>
  <div style="font-size:13px;color:{head};margin:6px 0 12px">{html.escape(company)}</div>
  <div style="font-size:13px;font-weight:700;color:{head};margin-top:8px">1. Who we are</div>
  <div style="font-size:12px;line-height:1.5;margin:4px 0 10px">Headings, body text and tables
    in your colour and font.</div>
  <table style="border-collapse:collapse;font-size:11px;width:100%">
    <tr><th style="background:{fill};color:{on_fill};text-align:left;padding:4px 6px">Purpose</th>
        <th style="background:{fill};color:{on_fill};text-align:left;padding:4px 6px">Kept for</th></tr>
    <tr><td style="border:1px solid #ccc;padding:4px 6px">Customer accounts</td>
        <td style="border:1px solid #ccc;padding:4px 6px">3 years</td></tr>
  </table>
  <div style="font-size:10px;color:#999;font-style:italic;margin-top:14px">{footer}</div>
</div>""")


def render(client: dict, user_id: str) -> None:
    cid = client["id"]
    company = client.get("legal_name") or client.get("company_name") or ""
    st.subheader(tr("Document branding"))

    if not DT.branding_allowed(cid):
        st.caption(tr("Documents for this company use RECOSA's neutral style. With "
                   "Professional, they carry your logo, colour, font and footer line."))
        if st.button(tr("Upgrade to brand your documents"), key=f"brand_up_{cid}"):
            from tier_gates import upsell_dialog
            upsell_dialog("Document branding is part of Professional, Advisory and "
                          "Enterprise.")
        return

    row = DT.latest_profile(cid)
    logo = DT.load_logo(row.get("logo_path")) if row else None
    saved = DT.theme_from_row(row, logo) if row else DT.HOUSE

    st.caption(tr("Your logo, colour, font and footer line on every document RECOSA "
               "generates for this company — Word, PDF, ODT and Excel. Documents "
               "already generated keep their look; generate again to update them."))

    left, right = st.columns([1, 1], gap="large")
    with right:
        st.markdown("**Preview**" + ("" if saved.branded else " — RECOSA's neutral style"))
        _preview(saved, company)
        if saved.branded:
            from document_generator import build_docx
            st.download_button(
                tr("Download a sample document"), key=f"brand_sample_{cid}",
                data=build_docx(_SAMPLE, "privacy_policy", company, "en", theme=saved),
                file_name="RECOSA_branding_sample.docx",
                mime="application/vnd.openxmlformats-officedocument.wordprocessingml.document",
                use_container_width=True,
            )

    with left:
        if not can_edit(client.get("role")):
            st.info(tr("You can see this company's branding but not change it."))
            return
        with st.form(f"brand_form_{cid}"):
            enabled = st.toggle(tr("Use my branding on documents"),
                                value=bool(row.get("enabled")) if row else True,
                                key=f"brand_on_{cid}")
            up = st.file_uploader(tr("Logo (PNG or JPG, up to 5 MB)"), type=["png", "jpg", "jpeg"],
                                  key=f"brand_logo_{cid}",
                                  help=tr("A wide logo on a transparent or white background "
                                       "works best. It goes at the top of every page."))
            remove = False
            if row and row.get("logo_path"):
                remove = st.checkbox(tr("Remove the current logo"), key=f"brand_rm_{cid}")
            c1, c2 = st.columns([1, 2])
            color = c1.color_picker(tr("Main colour"), value=(row or {}).get("primary_color")
                                    or DT.HOUSE_COLOR, key=f"brand_col_{cid}")
            font = c2.selectbox(tr("Font"), DT.FONTS,
                                index=DT.FONTS.index((row or {}).get("font") or "Arial")
                                if (row or {}).get("font") in DT.FONTS else 0,
                                key=f"brand_font_{cid}")
            footer = st.text_input(tr("Footer line"), value=(row or {}).get("footer_text") or "",
                                   max_chars=200, key=f"brand_foot_{cid}",
                                   placeholder=tr("Acme SRL · BE 0123.456.789 · privacy@acme.eu"),
                                   help=tr("Shown at the end of each document, before the date "
                                        "and the review notice."))
            if st.form_submit_button(tr("Save branding"), type="primary"):
                logo_png = None
                if up is not None:
                    try:
                        logo_png = DT.prepare_logo(up.getvalue())
                    except ValueError as e:
                        st.error(str(e))
                        return
                keep = None if remove else (row or {}).get("logo_path")
                ok, err = DT.save_profile(cid, user_id, enabled=enabled, color=color,
                                          font=font, footer_text=footer,
                                          logo_png=logo_png, keep_logo_path=keep)
                if ok:
                    st.success(tr("Saved. New documents use it."))
                    st.rerun()
                else:
                    st.error(err)
        rgb = DT.hex_to_rgb(color)
        if DT.readable_on_white(rgb) != rgb:
            st.caption(tr("This colour is light, so headings use a darker shade of it "
                       "to stay readable. Rules and table headers keep it as chosen."))
        st.caption(tr("Fonts: the reader's Word or LibreOffice must have the font; "
                   "Arial, Georgia, Times New Roman and Verdana are on nearly every computer."))
