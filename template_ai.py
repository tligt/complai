def _t(language: str, key: str) -> str:
    return _T.get(language, _T["en"]).get(key, _T["en"][key])


def _fd(d: Any, language: str) -> str:
    import training_rules as TR  # noqa: PLC0415
    d = TR._d(d)
    return d.strftime("%d/%m/%Y") if d else ""


