def render_ai_approved_uses(context: Mapping[str, Any], language: str) -> Block:
    """Each AI system, each approved use on it, and whether personal data may
    go in. Systems with no approved use are listed as not to be used."""
    lang = language if language in _T else "en"
    block = Block(name="ai_approved_uses",
                  headers=[_t(lang, "tool"), _t(lang, "use"), _t(lang, "pd"), _t(lang, "risk")])
    for s in context.get("ai_systems") or []:
        uses = [u for u in context.get("ai_use_cases") or []
                if u["system_id"] == s["id"] and (u.get("status") or "in_use") == "in_use"
                and AR.classify(u)["risk"] != AR.PROHIBITED]
        dpa = (s.get("dpa_status") or "") == "signed"
        pd = _t(lang, "pd_yes") if dpa else _t(lang, "pd_no")
        if not uses:
            block.rows.append([s.get("name") or "", _t(lang, "no_use"), _t(lang, "pd_na"), "—"])
        for u in uses:
            block.rows.append([s.get("name") or "", u.get("name") or "", pd,
                               _RISK.get(lang, _RISK["en"])[AR.classify(u)["risk"]]])
    return block


def render_ai_prohibited(context: Mapping[str, Any], language: str) -> Block:
    lang = language if language in ("en", "fr") else "en"
    block = Block(name="ai_prohibited", headers=[_t(lang, "practice"), _t(lang, "article")])
    for r in context.get("ai_practices") or []:
        block.rows.append([r.get(f"label_{lang}") or r.get("label_en") or r["code"],
                           (r.get("metadata") or {}).get("article") or ""])
    return block


def render_ai_oversight(context: Mapping[str, Any], language: str) -> Block:
    """High-risk uses, who oversees each, and whether their training is current."""
    lang = language if language in _T else "en"
    block = Block(name="ai_oversight",
                  headers=[_t(lang, "use_col"), _t(lang, "system"), _t(lang, "overseer"), _t(lang, "training")])
    emp = {e["id"]: e for e in context.get("employees") or []}
    sys_by_id = {s["id"]: s for s in context.get("ai_systems") or []}
    status = context.get("oversight_training") or {}
    for u in context.get("ai_high_risk") or []:
        e = emp.get(u.get("oversight_employee_id"))
        cell = status.get(u.get("oversight_employee_id")) or {}
        st_ = cell.get("state")
        training = (_t(lang, "trained").format(d=_fd(cell.get("valid_until"), lang))
                    if st_ in ("current", "expiring") else
                    _t(lang, "lapsed") if st_ == "expired" else _t(lang, "untrained"))
        block.rows.append([u.get("name") or "", (sys_by_id.get(u["system_id"]) or {}).get("name") or "",
                           e.get("name") if e else _t(lang, "nobody"), training if e else "—"])
    if not block.rows:
        block.rows.append([_t(lang, "none_high"), "", "", ""])
    return block


def render_ai_notice(context: Mapping[str, Any], language: str) -> Block:
    """The uses people meet directly, and what each one means for them."""
    lang = language if language in _T else "en"
    block = Block(name="ai_notice", headers=[_t(lang, "where"), _t(lang, "what"), _t(lang, "know")])
    sys_by_id = {s["id"]: s for s in context.get("ai_systems") or []}
    for u in context.get("ai_notice_uses") or []:
        notes = []
        if u.get("interacts_with_people"):
            notes.append(_t(lang, "n_chat"))
        if u.get("generates_content"):
            notes.append(_t(lang, "n_gen"))
        if u.get("deep_fake"):
            notes.append(_t(lang, "n_fake"))
        if u.get("public_interest_text"):
            notes.append(_t(lang, "n_text"))
        if u.get("emotion_or_biometric"):
            notes.append(_t(lang, "n_emotion"))
        block.rows.append([u.get("name") or "",
                           u.get("description") or (sys_by_id.get(u["system_id"]) or {}).get("name") or "",
                           " ".join(notes)])
    if not block.rows:
        block.rows.append([_t(lang, "none_notice"), "", ""])
    return block


