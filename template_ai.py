def build_ai_context_from(systems, use_cases, practices, employees, training) -> dict[str, Any]:
    """The pure half of build_ai_block_context, for tests."""
    import training_rules as TR  # noqa: PLC0415
    from datetime import date  # noqa: PLC0415
    ai_systems = sorted([s for s in systems if AR.is_ai_system(s)], key=lambda s: (s.get("name") or "").lower())
    sys_by_id = {s["id"]: s for s in ai_systems}
    ucs = [u for u in use_cases if (u.get("status") or "in_use") == "in_use" and u["system_id"] in sys_by_id]
    high = [u for u in ucs if AR.classify(u)["risk"] == AR.HIGH
            and AR.effective_role(u, sys_by_id.get(u["system_id"]))[0] == "deployer"]
    status: dict[str, Any] = {}
    reqs = [r for r in (training or {}).get("requirements") or [] if r["code"] == "ai_oversight"]
    if reqs:
        mx = TR.matrix(employees, reqs, training.get("sessions") or [], training.get("attendance") or [],
                       date.today())
        status = {eid: row["ai_oversight"] for eid, row in mx.items()}
    return {
        "ai_systems": ai_systems,
        "ai_use_cases": ucs,
        "ai_practices": practices,
        "ai_high_risk": high,
        "ai_notice_uses": [u for u in ucs if any(u.get(k) for k in _NOTICE_KEYS)],
        "employees": employees,
        "oversight_training": status,
    }


def build_ai_block_context(client_id: str, language: str) -> tuple[dict[str, Any], str | None]:
    from template_store import _get_client  # noqa: PLC0415
    import training_rules as TR  # noqa: PLC0415
    sb = _get_client()

    def rows(table, **eq):
        q = sb.table(table).select("*")
        for k, v in eq.items():
            q = q.eq(k, v)
        return q.execute().data or []

    try:
        practices = (sb.table("reference_values").select("*").eq("value_type", "ai_prohibited_practice")
                     .eq("active", True).is_("workspace_id", "null").order("sort_order").execute().data or [])
        reqs = [TR.requirement(r) for r in
                (sb.table("reference_values").select("*").eq("value_type", "training_requirement")
                 .is_("workspace_id", "null").execute().data or [])]
        ctx = build_ai_context_from(
            rows("systems", client_id=client_id), rows("ai_use_cases", client_id=client_id),
            practices, rows("employees", client_id=client_id),
            {"requirements": reqs, "sessions": rows("training_sessions", client_id=client_id),
             "attendance": rows("training_attendance", client_id=client_id)})
    except Exception as e:
        return {}, f"Could not read the AI inventory: {e}"
    stamps = [u.get("updated_at") for u in ctx["ai_use_cases"] if u.get("updated_at")]
    return ctx, (max(stamps)[:10] if stamps else None)


def apply_ai_values(values: dict[str, Any], client: Mapping[str, Any],
                    block_context: Mapping[str, Any] | None, language: str) -> None:
    ctx = block_context or {}
    values["ai_policy_owner"] = (client.get("ai_policy_owner") or "").strip()
    values["has_legal_form"] = bool((client.get("legal_form") or "").strip())
    values["has_policy_effective_date"] = bool(values.get("policy_effective_date"))

    ucs = ctx.get("ai_use_cases") or []
    systems = ctx.get("ai_systems") or []
    values["has_ai_uses"] = bool(ucs)
    values["has_generative"] = any(u.get("generates_content") for u in ucs)
    values["has_unapproved_systems"] = any(not any(u["system_id"] == s["id"] for u in ucs) for s in systems)

    high = ctx.get("ai_high_risk") or []
    status = ctx.get("oversight_training") or {}
    values["has_high_risk"] = bool(high)
    values["has_unassigned"] = any(not u.get("oversight_employee_id") for u in high)
    values["has_untrained"] = any(
        u.get("oversight_employee_id") and (status.get(u["oversight_employee_id"]) or {}).get("state")
        not in ("current", "expiring") for u in high)
    values["has_workers"] = any(u.get("used_on_workers") for u in high)

    notice = ctx.get("ai_notice_uses") or []
    values["has_notice_uses"] = bool(notice)
    values["has_deep_fake"] = any(u.get("deep_fake") for u in notice)
    values["has_emotion"] = any(u.get("emotion_or_biometric") for u in notice)
